export function choiceRetry(family: FamilyId, index: number): string | undefined {
  const guide = guides[family];
  if (typeof guide === 'string') return guide;
  const stage = guide?.[Math.floor(index / 3)];
  return typeof stage === 'string' ? stage : stage?.[index % 3];
}
